const assert=require('node:assert/strict');
const L=require('../assets/calendar-views.js');
const fs=require('node:fs'),path=require('node:path');
const source=fs.readFileSync(path.join(__dirname,'../assets/calendar-views.js'),'utf8');
const css=fs.readFileSync(path.join(__dirname,'../assets/calendar-views.css'),'utf8');
const view=fs.readFileSync(path.join(__dirname,'../partials/calendar_views.php'),'utf8');
let checks=0;
const check=(name,fn)=>{fn();checks++;console.log('PASS:',name);};
const ev=(id,start,end,extra={})=>({id,start_datetime:start,end_datetime:end,...extra});
check('weeks start Monday across month boundary',()=>assert.equal(L.monday('2026-09-01'),'2026-08-31'));
check('Sunday belongs to same Monday week',()=>assert.equal(L.monday('2026-09-06'),'2026-08-31'));
check('leap day navigation',()=>assert.equal(L.add('2028-02-28',1),'2028-02-29'));
check('December year boundary',()=>assert.equal(L.add('2026-12-31',1),'2027-01-01'));
check('wall time does not depend on system timezone',()=>assert.equal(L.parse('2026-09-04 09:30:00').getUTCHours(),9));
const a=ev(1,'2026-09-04 09:00:00','2026-09-04 10:30:00');
const b=ev(2,'2026-09-04 10:00:00','2026-09-04 11:00:00');
const c=ev(3,'2026-09-04 12:00:00','2026-09-04 13:00:00');
const positioned=L.positioned([a,b,c],'2026-09-04');
check('actual start minute',()=>assert.equal(positioned[0].start,540));
check('actual 90 minute duration',()=>assert.equal(positioned[0].end-positioned[0].start,90));
check('overlapping events get separate lanes',()=>assert.notEqual(positioned[0].lane,positioned[1].lane));
check('overlap width group',()=>assert.equal(positioned[0].lanes,2));
check('later nonoverlapping event gets full width',()=>assert.equal(positioned[2].lanes,1));
const overnight=ev(4,'2026-09-03 23:00:00','2026-09-04 02:00:00');
check('overnight event included on next day',()=>assert.ok(L.onDay(overnight,'2026-09-04')));
check('overnight event clipped to day boundary',()=>assert.equal(L.positioned([overnight],'2026-09-04')[0].start,0));
check('midnight end excluded from next day',()=>assert.equal(L.onDay(ev(5,'2026-09-03 22:00:00','2026-09-04 00:00:00'),'2026-09-04'),false));
const deadline=ev(6,'2026-09-04 23:59:00','2026-09-04 23:59:00',{assignment_test_id:1});
check('instant deadline included on its day',()=>assert.ok(L.onDay(deadline,'2026-09-04')));
check('instant deadline is not all-day',()=>assert.equal(L.allDay(deadline),false));
check('full-day midnight interval gets all-day row',()=>assert.ok(L.allDay(ev(7,'2026-09-04 00:00:00','2026-09-05 00:00:00'))));
check('mobile day and week share duration-faithful timeline',()=>assert.ok(source.includes('cvMobileTimeline(selectedDate)')&&source.includes('duration/60*hourHeight')));
check('mobile overlap layout stays lane-aware',()=>assert.ok(source.includes('row.lanes===2?58')&&source.includes('row.lane*(100-width)/(row.lanes-1)')));
check('week strip exposes event indicators',()=>assert.ok(source.includes('cv-strip-dots')&&source.includes('events.slice(0,3)')));
check('add event is a primary mobile action outside filters',()=>assert.ok(view.indexOf('class="btn primary cv-mobile-add"')<view.indexOf('<details class="cv-filters"')));
check('mobile calendar prevents horizontal overflow and docks feedback away from events',()=>assert.ok(css.includes('overflow-x:clip')&&source.includes("brand.insertBefore(feedback,todayButton)")&&css.includes('.cv-mobile-brand .feedback-fab')));
console.log(`${checks} calendar layout checks passed.`);
